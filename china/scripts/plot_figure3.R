prefix <- file.path(out,'Fig_3')
draw_whole <- function(measure=FALSE) {
  grid.newpage()
  pushViewport(viewport(x=unit(0,'mm'),y=unit(106,'mm'),width=unit(183,'mm'),height=unit(134,'mm'),
    just=c('left','bottom'),name='species-section'))
  s <- draw_species_sections(measure=measure);upViewport()
  pushViewport(viewport(x=unit(0,'mm'),y=unit(0,'mm'),width=unit(183,'mm'),height=unit(106,'mm'),
    just=c('left','bottom'),name='maps-section'))
  m <- draw_map_sections(measure=measure);upViewport()
  invisible(c(s,m))
}
